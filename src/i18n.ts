const dictionaries:Record<Lang,Record<Key,string>>={zh,en}
const htmlLang:Record<Lang,string>={zh:'zh-CN',en:'en'}

function readLang():Lang{
 // Chinese is the default; a choice is remembered on this device only.
 try{return window.localStorage.getItem(langStorageKey)==='en'?'en':'zh'}catch{return'zh'}
}
function applyDocument(lang:Lang){
 if(typeof document==='undefined')return
 document.documentElement.lang=htmlLang[lang]
 document.title=dictionaries[lang]['app.title']
}

interface LangState{lang:Lang;setLang:(lang:Lang)=>void}
export const useLang=create<LangState>(set=>({
 lang:typeof window==='undefined'?'zh':readLang(),
 setLang:lang=>{
  try{window.localStorage.setItem(langStorageKey,lang)}catch{/* blocked storage: the choice lasts for this session */}
  applyDocument(lang)
  set({lang})
 },
}))
if(typeof window!=='undefined')applyDocument(useLang.getState().lang)

/**
 * Translate in the current language. Game logic calls this when it writes a message, so a notice
 * already on screen keeps the language it was written in; everything rendered from state re-translates.
 */
export function t(key:Key,params?:Record<string,string|number>){
 const text=dictionaries[useLang.getState().lang][key]
 return params?text.replace(/\{(\w+)\}/g,(match,name:string)=>name in params?String(params[name]):match):text
}

/** Subscribe a component to language changes; returns the same `t`. */
export function useT(){
 useLang(s=>s.lang)
 return t
}
